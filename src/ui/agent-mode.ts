/** 灵框 · 助手的两种工作模式（2026-09-26 两次定方向；2026-10-11 改名 + 落盘 + 换默认）
 *
 *  第一次用户说：「**我想让灵框平常是正常的聊天及工作，但是少数情况下有 agent 工作能力**」——
 *  当时把 `chat` 划成**零工具**（不注入动作协议）。当天用户纠正了这个划法：
 *  「**聊天模式也留一点灵框内部的工具吧，agent 模式是在灵框外工作用的**」。
 *
 *  ⇒ 两个模式**都有全部动作**（灵框内部 + 灵框外文件 + 联网，见 `agent-tools.ts`）——
 *    "灵框外"那条分界线后来也被填平了（片 1/片 2 把文件与联网加进两个模式）。差别只剩**自主程度**，
 *    所以 2026-10-11 按创作者的话把它们改叫「自动」/「一轮」：
 *     · `agent` = **自动**（**默认档**）：该用工具就用工具，需要时**连着走多步**
 *       （`src/ui/agent.ts` 的 `AGENT_ROUNDS = 8`）、批量活一次规划好。
 *       用户 2026-10-11：「**还有使用工具时能不能直接切换到 agent 模式（话说聊天模式真的有必要吗）**」
 *       —— "这一问该拨哪个档"本来就不该由创作者猜，所以默认就是它。
 *     · `chat` = **一轮**：一次提问**只做一个动作**，做完把结果说给创作者、等他决定下一步 —— 看得住。
 *
 *  ⚠️ 授权**不由模式决定**，而是 `src/ui/agent-perm.ts` 的两把旋钮（范围 × 询问）：
 *     模式管"它这次要多自主"，权限管"允许它做到哪一步"。写入一律走提议卡片/闸门。
 *
 *  ⚠️ **2026-10-11 起模式落盘**（`lingkuang-settings.agentMode`，用户选了「记着」）：
 *     上一版是"关掉面板就回默认、不进设置"（怕"少数情况"变成忘了切回来）。现在默认档 = 自动，
 *     而"收窄到一轮"是创作者**明确**的克制选择 —— 关掉面板就把它忘掉才是错的。
 *     AI 可以用 `set_mode` 动作切模式：**放宽**（→ agent）永远只出一张要创作者点「应用」的卡片
 *     （`agent-tools.ts` 的 `needsConfirm`），收窄（→ chat）随时生效。
 */
export type AgentMode = 'chat' | 'agent';

export const MODES: AgentMode[] = ['chat', 'agent'];

/** 默认档 = 自动（用户 2026-10-11 选）：用不用多步由"这一问要不要用工具"决定，不让他先猜档位 */
export const DEFAULT_MODE: AgentMode = 'agent';

export const MODE_LABEL: Record<AgentMode, string> = { chat: '一轮', agent: '自动' };

/** 面板上给用户看的一句话说明（切模式时立刻换） */
export const MODE_HINT: Record<AgentMode, string> = {
  chat: '一轮档：能查也能改，但一次只做一个动作（要它接着做完就切「自动」）；写入要过下面那关。',
  agent: '自动档：该用工具就用工具，需要时连着走多步、可批量改；写入照旧要过下面那关。',
};

/** 拼进系统提示的那一段（两个模式都返回内容 —— 两边都有动作，差别在自主程度）。
 *  ⚠️ 这里**不许**再写「你只能聊天 / 改不了灵框里的任何数据」那类话：两个模式都有动作，
 *  说反了模型要么拒绝动手、要么反过来谎报"已经改好了"（这是最伤信任的一类谎报）。 */
export function modePrompt(mode: AgentMode): string {
  if (mode === 'agent') {
    return [
      '【你现在是「自动」模式】该用工具就用工具：需要的话**连着做多步**（一次提问里先查、再改、',
      '看结果、继续做，直到事情办完 —— 我最多放你连着走 8 步）。批量活（一次建好几个事件、',
      '给一批设定加同一个字段）先把整批规划好再一次做完，别一条一条来回问。做完给一句总结。',
    ].join('');
  }
  return [
    '【你现在是「一轮」模式】你手上有全部动作（查设定与事件、改字段、建条目、改设置、',
    '读写灵框外的文件、联网搜索），但**一次提问只做一个动作**：做完把结果说给创作者，等他决定下一步。',
    '写入不会直接生效 —— 会先变成一张要他点「应用」的提议卡片，别宣称「已经改好了」。',
    '不需要动手时就平常说话，别为了用工具而用工具。',
  ].join('');
}
