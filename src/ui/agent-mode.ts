/** 灵框 · 助手的两种工作模式（用户 2026-09-26 两次定方向）
 *
 *  第一次用户说：「**我想让灵框平常是正常的聊天及工作，但是少数情况下有 agent 工作能力**」——
 *  当时把 `chat` 划成**零工具**（不注入动作协议）。当天用户纠正了这个划法：
 *  「**聊天模式也留一点灵框内部的工具吧，agent 模式是在灵框外工作用的**」。
 *
 *  ⇒ 现在两个模式**都有灵框内部的动作**（读 4 + 写 5 + 设置/模式，见 `agent-tools.ts`），
 *    差别只在**自主程度**（用户拍板：Agent = 多步自主 + 批量改）：
 *     · `chat`：一次提问**只做一个动作**，做完把结果说给创作者、等他决定下一步 —— 看得住。
 *     · `agent`：可以**连着走多步**（`agent.ts` 的 `AGENT_ROUNDS = 8`）、批量活一次规划好。
 *  ⚠️ 「灵框外」的能力（文件 / 命令 / 联网）**现在一个都没有**：`toolsPrompt()` 已把
 *     inner（今天这些内部动作）与将来的 outer 留好分层，加外部工具时只往里加一段。
 *
 *  ⚠️ 授权**不再由模式决定**，而是 `src/ui/agent-perm.ts` 的两把旋钮（范围 × 询问）：
 *     模式管"它这次要多自主"，权限管"允许它做到哪一步"。写入一律走提议卡片/闸门。
 *
 *  ⚠️ 模式**不落盘、不进设置**：面板每次打开都从 `chat` 开始 —— 否则「少数情况」会变成
 *     "忘了切回来"，下次一开口它就自己连着干一长串。AI 可以用 `set_mode` 动作切模式，但
 *     **放宽**（→ agent）永远只出一张要创作者点「应用」的卡片（`agent-tools.ts` 的
 *     `needsConfirm`），收窄（→ chat）随时生效。
 */
export type AgentMode = 'chat' | 'agent';

export const MODES: AgentMode[] = ['chat', 'agent'];

export const MODE_LABEL: Record<AgentMode, string> = { chat: '聊天', agent: 'Agent' };

/** 面板上给用户看的一句话说明（切模式时立刻换） */
export const MODE_HINT: Record<AgentMode, string> = {
  chat: '聊天模式：能查、也能改，一次只做一个动作；写入要过下面那关。',
  agent: 'Agent 模式：能连着走多步、一次规划批量改；写入照旧要过下面那关。',
};

/** 拼进系统提示的那一段（两个模式都返回内容 —— 现在两边都有动作，差别在自主程度）。
 *  ⚠️ 这里**不许**再写「你只能聊天 / 改不了灵框里的任何数据」那类话：chat 现在有动作，
 *  说反了模型要么拒绝动手、要么反过来谎报"已经改好了"（这是最伤信任的一类谎报）。 */
export function modePrompt(mode: AgentMode): string {
  if (mode === 'agent') {
    return [
      '【你现在是「Agent」模式】你可以**连着做多步**：一次提问里先查、再改、看结果、继续做，',
      '直到事情办完（我最多放你连着走 8 步）。批量活（一次建好几个事件、给一批设定加同一个字段）',
      '先把整批规划好再一次做完，别一条一条来回问。做完给一句总结。',
    ].join('');
  }
  return [
    '【你现在是「聊天」模式】你手上有灵框内部的动作（查设定与事件、改字段、建条目、改设置），',
    '但**一次提问只做一个动作**：做完把结果说给创作者，等他决定下一步。',
    '写入不会直接生效 —— 会先变成一张要他点「应用」的提议卡片，别宣称「已经改好了」。',
    '不需要动手时就平常说话，别为了用工具而用工具。',
  ].join('');
}
