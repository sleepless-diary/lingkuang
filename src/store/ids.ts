/** 灵框 · id 生成（实体 / 节点 / 时间线 / 地图 / 剧情线都用它）
 *
 *  ⚠️ 为什么不能直接 `'e' + Date.now()`（原来六处都是这么写的）：毫秒精度不够。
 *  工作台顶栏那个「数量」框能一次建 20 个条目，循环在**同一毫秒**里就跑完了 ⇒ 拿到同一个 id
 *  ⇒ `entities[id] = …`（对象按 id 存）后建的把先建的**覆盖**掉。
 *  实测：点一次「＋新建实体（数量 3）」只活下来 2 个，而且名字是 `新实体 / 新实体 3`
 *  （中间的 `新实体 2` 连 JSON 带 vault 一起没了）—— **静默丢数据**，界面上只看见少了一行。
 *
 *  这里用「**单调时钟**」：以 `Date.now()` 打底，同一毫秒内依次 +1。
 *  ① 永不重复；② id 仍是"前缀 + 十进制数字"，看数字就知道什么时候建的，排序语义与原来一致；
 *  ③ 格式没变（vault 的文件名不含 id，历史数据照旧）。
 */
let lastStamp = 0;

/** 生成一个唯一 id（`prefix` 是集合前缀：`e` 实体 / `n` 节点 / `tl` 时间线 / `m` 地图 / `lg` 图层…） */
export function uid(prefix: string): string {
  const n = Math.max(Date.now(), lastStamp + 1);
  lastStamp = n;
  return prefix + n;
}
